export function normalizeFeatureName(name) {
  let n = String(name || '');
  n = n.replace(/^\[[^\]]*\]\s*/, ''); // multiclass prefix "[Fighter] "
  n = n.replace(/\s*\(.*\)\s*$/, '');  // "(2/day)", "(d6)", "(2 options)"…
  n = n.replace(/\s*\+\d+ft\s*$/, '');  // "+10ft"
  n = n.trim();
  return n;
}

export function featureDescription(name) {
  if (FEATURE_DESCRIPTIONS[name]) return FEATURE_DESCRIPTIONS[name];
  if (SUBCLASS_DESCRIPTIONS[name]) return SUBCLASS_DESCRIPTIONS[name];
  const norm = normalizeFeatureName(name);
  if (norm !== name && FEATURE_DESCRIPTIONS[norm]) return FEATURE_DESCRIPTIONS[norm];
  if (norm !== name && SUBCLASS_DESCRIPTIONS[norm]) return SUBCLASS_DESCRIPTIONS[norm];
  return null;
}
